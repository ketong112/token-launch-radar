// Token Radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// the 80 pre-token protocols below the watchlist floor with the highest implied value: the early
// rows the radar exists to find. A protocol is pre-token when its DefiLlama record carries no
// token (no market cap, no CoinGecko id, no symbol); the snapshot's live-token protocols are
// kept apart and shown as the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures:
//
//   sector     = median mcap/TVL of the snapshot's live-token protocols in the same category
//                (fewer than 3 live protocols: the global live median), clamped to [0.05, 1.0]
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.04 x min(max(chains - 1, 0), 5)
//   implied    = max(1, round(tvl_usd x sector x growthMult x maturity x breadth))
//
// The sector multiple is the model's one idea: the live market's own multiples calibrate what a
// new token in the same sector is worth, so a DEX is not scored like a bridge. It is computed
// from the snapshot at runtime, never hardcoded, and no protocol name is ever special-cased:
// the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_step: number;
  breadth_cap: number;
  sector_floor: number;
  sector_cap: number;
  sector_min_live: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  breadth_step: 0.04,
  breadth_cap: 5,
  sector_floor: 0.05,
  sector_cap: 1.0,
  sector_min_live: 3,
};

